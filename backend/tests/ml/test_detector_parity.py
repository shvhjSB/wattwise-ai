"""The browser's port of the default detector (T067) must find exactly what Python finds.

This builds a **synthetic** hourly series with known anomalies, gaps and missing values, runs the
default detector (the rolling same-hour z-score, D030) on it, and compares the result with the
committed fixture `frontend/src/features/meter/detector-parity.json`. The frontend test runs its
TypeScript port on the same input and must produce the same events. So the fixture can never
drift from the Python detector without one of the two tests failing.

To regenerate the fixture after a deliberate change to the detector:

    WATTWISE_UPDATE_PARITY=1 uv run pytest tests/ml/test_detector_parity.py
"""

import json
import os
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from wattwise.ml.detection import (
    DETECTOR_DEFAULTS,
    Detector,
    DetectorConfig,
    detect,
    rolling_same_hour,
)

FIXTURE = (
    Path(__file__).resolve().parents[3] / "frontend" / "src" / "features" / "meter"
) / "detector-parity.json"
START = pd.Timestamp("2017-01-02T00:00Z")
DAYS = 35


def series() -> pd.DataFrame:
    """Hourly readings: a daily cycle with noise, plus a 5-hour surge, a one-hour spike, a
    6-hour drop, two missing values and a 5-hour gap with no rows at all."""
    index = pd.date_range(START, periods=DAYS * 24, freq="h")
    hours = np.asarray(index.hour, dtype=float)
    noise = np.random.default_rng(7).normal(0, 0.3, len(index))
    values = np.round(10 + 5 * np.sin(2 * np.pi * hours / 24) + noise, 3)
    frame = pd.DataFrame({"timestamp": index, "value": values})

    def hours_of(day: int, first: int, count: int) -> pd.Series:
        stamp = frame["timestamp"]
        begin = START + pd.Timedelta(days=day, hours=first)
        return (stamp >= begin) & (stamp < begin + pd.Timedelta(hours=count))

    frame.loc[hours_of(20, 10, 5), "value"] += 8.0  # a surge
    frame.loc[hours_of(24, 3, 1), "value"] += 25.0  # a spike
    frame.loc[hours_of(27, 0, 6), "value"] -= 4.0  # a drop
    frame.loc[hours_of(22, 5, 2), "value"] = np.nan  # missing values, rows present
    frame = frame[~hours_of(25, 12, 5)].reset_index(drop=True)  # a gap: no rows
    frame["value"] = frame["value"].round(3)
    frame["meter_id"] = "m"
    frame["building_id"] = "b"
    return frame


def events(frame: pd.DataFrame) -> list[dict[str, Any]]:
    config = DetectorConfig(**DETECTOR_DEFAULTS[Detector.ROLLING_Z])  # type: ignore[arg-type]
    z, baseline = rolling_same_hour(frame, floor_fraction=config.scale_floor_fraction)
    found = detect(frame, baseline, None, np.ones(len(frame), dtype=bool), config, z=z).events
    records: list[dict[Any, Any]] = found.to_dict("records")
    return [
        {
            "direction": str(row["direction"]),
            "start": _iso(row["start"]),
            "end": _iso(row["end"]),
            "duration_hours": int(row["duration_hours"]),
            "flagged_hours": int(row["flagged_hours"]),
            "missing_hours": int(row["missing_hours"]),
            "peak_time": _iso(row["peak_time"]),
            "peak_z": float(row["peak_z"]),
            "peak_residual": float(row["peak_residual"]),
            "residual_sum": float(row["residual_sum"]),
            "ongoing": bool(row["ongoing"]),
        }
        for row in records
    ]


def _iso(value: Any) -> str:
    return pd.Timestamp(value).isoformat().replace("+00:00", "Z")


def fixture() -> dict[str, Any]:
    frame = series()
    return {
        "note": "Synthetic. Generated by backend/tests/ml/test_detector_parity.py; do not edit.",
        "config": DetectorConfig(**DETECTOR_DEFAULTS[Detector.ROLLING_Z]).model_dump(),  # type: ignore[arg-type]
        "rows": [
            [pd.Timestamp(t).isoformat().replace("+00:00", "Z"), None if np.isnan(v) else v]
            for t, v in zip(frame["timestamp"], frame["value"].astype(float), strict=True)
        ],
        "events": events(frame),
    }


def test_the_series_has_the_anomalies_it_was_built_with() -> None:
    found = events(series())
    directions = sorted(e["direction"] for e in found)

    assert "high" in directions and "low" in directions
    starts = {e["start"] for e in found}
    assert "2017-01-22T10:00:00Z" in starts  # the surge
    assert "2017-01-26T03:00:00Z" in starts  # the spike, kept by z_spike


def test_the_committed_fixture_matches_the_python_detector() -> None:
    expected = fixture()
    if os.environ.get("WATTWISE_UPDATE_PARITY"):
        FIXTURE.write_text(json.dumps(expected, indent=1) + "\n", encoding="utf-8")
    committed = json.loads(FIXTURE.read_text(encoding="utf-8"))

    assert committed == json.loads(json.dumps(expected))
