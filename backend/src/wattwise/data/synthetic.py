#: Decimal places written for each numeric column.
_DECIMALS: Final = {
    "value": 3,
    "air_temperature_c": 1,
    "dew_temperature_c": 1,
    "wind_speed_m_s": 1,
    "floor_area_m2": 0,
    "effect_value": 2,
}

FILES: Final = (
    "readings.csv",
    "buildings.csv",
    "weather.csv",
    "anomaly_labels.csv",
    "README.md",
)


@dataclass(frozen=True)
class SyntheticDataset:
    """Canonical tables plus the anomaly labels. `clean_readings` are the readings before
    injection: the ground-truth counterfactual, kept in memory but not written."""

    seed: int
    readings: pd.DataFrame
    clean_readings: pd.DataFrame
    buildings: pd.DataFrame
    weather: pd.DataFrame
    labels: pd.DataFrame


def timestamps() -> pd.DatetimeIndex:
    return pd.date_range(START, periods=DAYS * 24, freq="h", tz="UTC", unit="us")


def generate(seed: int = DEFAULT_SEED) -> SyntheticDataset:
    """Generate the synthetic dataset. Deterministic for a given seed."""
    rng = np.random.default_rng(seed)
    index = timestamps()

    temperatures: dict[str, FloatArray] = {}
    weather_parts: list[pd.DataFrame] = []
    for site in SYNTHETIC_SITES:
        air, dew, wind = _site_weather(site, index, rng)
        temperatures[site.site_id] = air
        weather_parts.append(
            pd.DataFrame(
                {
                    "site_id": site.site_id,
                    "timestamp": index,
                    "air_temperature_c": _round(air, "air_temperature_c"),
                    "dew_temperature_c": _round(dew, "dew_temperature_c"),
                    "wind_speed_m_s": _round(wind, "wind_speed_m_s"),
                }
            )
        )

    timezones = {site.site_id: site.timezone for site in SYNTHETIC_SITES}
    clean_parts: list[pd.DataFrame] = []
    injected_parts: list[pd.DataFrame] = []
    for building in SYNTHETIC_BUILDINGS:
        local = index.tz_convert(timezones[building.site_id])
        clean = _building_load(building, local, temperatures[building.site_id], rng)
        injected = clean.copy()
        for anomaly in INJECTED_ANOMALIES:
            if anomaly.building_id == building.building_id:
                injected = _inject(injected, index, local, anomaly)
        clean_parts.append(_readings_frame(building, index, clean))
        injected_parts.append(_readings_frame(building, index, injected))

    buildings = pd.DataFrame(
        {
            "building_id": [b.building_id for b in SYNTHETIC_BUILDINGS],
            "site_id": [b.site_id for b in SYNTHETIC_BUILDINGS],
            "timezone": [timezones[b.site_id] for b in SYNTHETIC_BUILDINGS],
            "primary_use": [b.primary_use for b in SYNTHETIC_BUILDINGS],
            "floor_area_m2": [float(b.floor_area_m2) for b in SYNTHETIC_BUILDINGS],
        }
    )
    return SyntheticDataset(
        seed=seed,
        readings=to_canonical(pd.concat(injected_parts, ignore_index=True), READINGS),
        clean_readings=to_canonical(pd.concat(clean_parts, ignore_index=True), READINGS),
        buildings=to_canonical(buildings, BUILDINGS),
        weather=to_canonical(pd.concat(weather_parts, ignore_index=True), WEATHER),
        labels=_labels_frame(),
    )


def write(dataset: SyntheticDataset, directory: Path) -> dict[str, str]:
    """Write the dataset, its README and manifest. Returns file name -> SHA-256."""
    directory.mkdir(parents=True, exist_ok=True)
    contents = {
        "readings.csv": _csv_text(dataset.readings),
        "buildings.csv": _csv_text(dataset.buildings),
        "weather.csv": _csv_text(dataset.weather),
        "anomaly_labels.csv": _csv_text(dataset.labels),
        "README.md": _readme(dataset),
    }
    rows = {
        "readings.csv": len(dataset.readings),
        "buildings.csv": len(dataset.buildings),
        "weather.csv": len(dataset.weather),
        "anomaly_labels.csv": len(dataset.labels),
    }
    digests: dict[str, str] = {}
    manifest_files: dict[str, dict[str, object]] = {}
    for name in FILES:
        data = contents[name].encode("utf-8")
        (directory / name).write_bytes(data)
        digests[name] = hashlib.sha256(data).hexdigest()
        entry: dict[str, object] = {"bytes": len(data), "sha256": digests[name]}
        if name in rows:
            entry["rows"] = rows[name]
        manifest_files[name] = entry

    manifest = {
        "notice": NOTICE,
        "generator": "wattwise.data.synthetic",
        "generator_version": GENERATOR_VERSION,
        "seed": dataset.seed,
        "contract_version": CONTRACT_VERSION,
        "period_start": _iso(START),
        "period_end_exclusive": _iso(START + pd.Timedelta(days=DAYS)),
        "files": manifest_files,
    }
    manifest_data = (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode("utf-8")
    (directory / "manifest.json").write_bytes(manifest_data)
    digests["manifest.json"] = hashlib.sha256(manifest_data).hexdigest()
    return digests


# ---------------------------------------------------------------------------
# Models
# ---------------------------------------------------------------------------


def _ar1(rng: np.random.Generator, n: int, phi: float, sd: float) -> FloatArray:
    """Stationary AR(1) noise with marginal standard deviation `sd`."""
    shocks = rng.standard_normal(n)
    out = np.empty(n)
    out[0] = sd * shocks[0]
    scale = sd * np.sqrt(1.0 - phi**2)
    for t in range(1, n):
        out[t] = phi * out[t - 1] + scale * shocks[t]
    return out


def _local_hours(local: pd.DatetimeIndex) -> FloatArray:
    return local.hour.to_numpy(dtype=float) + local.minute.to_numpy(dtype=float) / 60.0


def _site_weather(
    site: Site, index: pd.DatetimeIndex, rng: np.random.Generator
) -> tuple[FloatArray, FloatArray, FloatArray]:
    local = index.tz_convert(site.timezone)
    hours = _local_hours(local)
    local_days = local.normalize().tz_localize(None)
    day = (local_days - local_days[0]).days.to_numpy()
    daily = _ar1(rng, int(day.max()) + 1, phi=0.7, sd=site.daily_sd_c)
    diurnal = np.cos(2.0 * np.pi * (hours - 15.0) / 24.0)  # warmest at 15:00 local
    elapsed_days = np.arange(len(index)) / 24.0
    air = (
        site.mean_temperature_c
        + site.warming_c_per_day * elapsed_days
        + daily[day]
        + site.diurnal_amplitude_c * diurnal
        + _ar1(rng, len(index), phi=0.8, sd=0.6)
    )
    spread = 2.5 + 1.5 * (1.0 + diurnal) + np.abs(_ar1(rng, len(index), phi=0.9, sd=0.5))
    wind = np.exp(np.log(3.5) + _ar1(rng, len(index), phi=0.9, sd=0.35))
    return air, air - spread, wind


def _sigmoid(x: FloatArray) -> FloatArray:
    result: FloatArray = 1.0 / (1.0 + np.exp(-x))
    return result


def _building_load(
    building: Building,
    local: pd.DatetimeIndex,
    temperature: FloatArray,
    rng: np.random.Generator,
) -> FloatArray:
    hours = _local_hours(local)
    occupancy = _sigmoid((hours - building.opens_hour) / 0.6) * _sigmoid(
        (building.closes_hour - hours) / 0.6
    )
    weekend = local.dayofweek.to_numpy() >= 5
    occupancy = np.where(weekend, occupancy * building.weekend_occupancy, occupancy)
    heating = building.heating_kw_per_c * np.maximum(0.0, BALANCE_POINT_C - temperature)
    noise = _ar1(rng, len(local), phi=0.6, sd=building.noise_sd)
    load: FloatArray = (building.base_kw + building.occupied_kw * occupancy + heating) * (
        1.0 + noise
    )
    return load


def _inject(
    values: FloatArray,
    index: pd.DatetimeIndex,
    local: pd.DatetimeIndex,
    anomaly: Anomaly,
) -> FloatArray:
    out = values.copy()
    window = np.asarray((index >= anomaly.start) & (index < anomaly.end))
    positions = np.flatnonzero(window)
    if anomaly.effect is Effect.MULTIPLY:
        out[window] *= _required(anomaly)
    elif anomaly.effect is Effect.ADD_AT_NIGHT:
        hours = local.hour.to_numpy()
        night = (hours >= NIGHT_START_HOUR) | (hours < NIGHT_END_HOUR)
        out[window & night] += _required(anomaly)
    elif anomaly.effect is Effect.RAMP_TO:
        fraction = np.arange(1, len(positions) + 1) / len(positions)
        out[positions] *= 1.0 + (_required(anomaly) - 1.0) * fraction
    elif anomaly.effect is Effect.HOLD:
        out[positions] = out[positions[0]]
    elif anomaly.effect is Effect.REMOVE:
        out[positions] = np.nan
    return out


def _required(anomaly: Anomaly) -> float:
    if anomaly.effect_value is None:
        raise ValueError(f"{anomaly.event_id}: effect {anomaly.effect} needs an effect_value")
    return anomaly.effect_value


