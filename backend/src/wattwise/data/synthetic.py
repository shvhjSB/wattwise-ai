# Frames and files
# ---------------------------------------------------------------------------


def _round(values: FloatArray, column: str) -> FloatArray:
    # Adding 0.0 turns -0.0 into 0.0, so files never contain "-0.0".
    rounded: FloatArray = np.round(values, _DECIMALS[column]) + 0.0
    return rounded


def _readings_frame(
    building: Building, index: pd.DatetimeIndex, values: FloatArray
) -> pd.DataFrame:
    return pd.DataFrame(
        {
            "timestamp": index,
            "meter_id": building.meter_id,
            "building_id": building.building_id,
            "meter_type": MeterType.ELECTRICITY.value,
            "unit": Unit.KWH.value,
            "value": _round(values, "value"),
        }
    )


def _labels_frame() -> pd.DataFrame:
    meters = {b.building_id: b.meter_id for b in SYNTHETIC_BUILDINGS}
    return pd.DataFrame(
        {
            "event_id": [a.event_id for a in INJECTED_ANOMALIES],
            "anomaly_type": [a.anomaly_type.value for a in INJECTED_ANOMALIES],
            "meter_id": [meters[a.building_id] for a in INJECTED_ANOMALIES],
            "building_id": [a.building_id for a in INJECTED_ANOMALIES],
            "start": pd.to_datetime([a.start for a in INJECTED_ANOMALIES], utc=True).as_unit("us"),
            "end": pd.to_datetime([a.end for a in INJECTED_ANOMALIES], utc=True).as_unit("us"),
            "effect": [a.effect.value for a in INJECTED_ANOMALIES],
            "effect_value": [
                np.nan if a.effect_value is None else a.effect_value for a in INJECTED_ANOMALIES
            ],
            "description": [a.description for a in INJECTED_ANOMALIES],
            "label_source": LABEL_SOURCE,
        }
    )


def _iso(timestamp: pd.Timestamp) -> str:
    return timestamp.tz_convert("UTC").strftime("%Y-%m-%dT%H:%M:%SZ")


def _csv_text(frame: pd.DataFrame) -> str:
    """Render a frame as CSV with fixed, platform-independent formatting."""
    text = pd.DataFrame(index=frame.index)
    for name in frame.columns:
        column = frame[name]
        if isinstance(column.dtype, pd.DatetimeTZDtype):
            text[name] = column.dt.strftime("%Y-%m-%dT%H:%M:%SZ")
        elif pd.api.types.is_float_dtype(column.dtype):
            digits = _DECIMALS.get(str(name), 3)
            text[name] = [
                "" if np.isnan(v) else f"{v:.{digits}f}"
                for v in column.to_numpy(dtype=float, na_value=np.nan)
            ]
        else:
            text[name] = column.astype(object).where(column.notna(), "")
    return text.to_csv(index=False, lineterminator="\n")


def _readme(dataset: SyntheticDataset) -> str:
    sites = "\n".join(
        f"| `{s.site_id}` | `{s.timezone}` | {s.mean_temperature_c:g} | {s.diurnal_amplitude_c:g} |"
        for s in SYNTHETIC_SITES
    )
    buildings = "\n".join(
        f"| `{b.building_id}` | `{b.site_id}` | {b.primary_use} | {b.base_kw:g} | "
        f"{b.occupied_kw:g} | {b.opens_hour:g}-{b.closes_hour:g} | {b.weekend_occupancy:g} | "
        f"{b.heating_kw_per_c:g} |"
        for b in SYNTHETIC_BUILDINGS
    )
    anomalies = "\n".join(
        f"| `{a.event_id}` | `{a.anomaly_type.value}` | `{a.building_id}` | {_iso(a.start)} | "
        f"{_iso(a.end)} | {a.description} |"
        for a in INJECTED_ANOMALIES
    )
    end = START + pd.Timedelta(days=DAYS)
    return f"""# Synthetic sample data

> **{NOTICE}**

This folder is generated: do not edit it by hand. Regenerate it with:

```bash
cd backend
uv run python -m wattwise.data.synthetic --output ../data/sample/synthetic --seed {dataset.seed}
```

- **Generator:** `wattwise.data.synthetic`, version {GENERATOR_VERSION}. The seed controls noise
  only; the scenario below is fixed. This copy uses seed {dataset.seed}.
- **Data contract:** version {CONTRACT_VERSION} (`docs/DATA_CONTRACT.md`). Every table here
  passes validation.
- **Period:** {_iso(START)} to {_iso(end)} (end exclusive), hourly, {DAYS} days.
- **Files:**
  - `readings.csv`: hourly electricity in kWh, with the anomalies below injected.
  - `buildings.csv`, `weather.csv`: the matching building metadata and site weather.
  - `anomaly_labels.csv`: the injected events.
  - `manifest.json`: hashes and row counts.
- **Purpose:** tests, the demo mode and injected-anomaly benchmarks. Results on this data are
  **synthetic benchmark results**, not evidence of real-world performance.

## Sites (synthetic weather)

| Site | Time zone | Mean temperature (degC) | Diurnal amplitude (degC) |
|---|---|---|---|
{sites}

Air temperature has a slow warming trend, day-to-day variation (AR(1)), a daily cycle peaking at
15:00 local time, and hourly noise. Dew point stays below air temperature. Wind speed is
log-normal.

## Buildings (synthetic load model)

Load in kWh per hour = (base + occupied x occupancy + heating) x (1 + noise). Occupancy follows
smooth opening hours in **local** time and is scaled down at weekends. Electric heating adds the
heating coefficient per degC below {BALANCE_POINT_C:g} degC.

| Building | Site | Use | Base kW | Occupied kW | Open (local h) | Weekend | Heating kW/degC |
|---|---|---|---|---|---|---|---|
{buildings}

Hourly load and temperature can correlate *positively*, because both peak in the afternoon. The
heating effect shows on daily averages, where load falls as temperature rises for every
building; a test checks this.

Not modelled: public holidays, daylight-saving transitions (none fall in this period),
equipment-level loads, and any event not listed below.

## Injected anomalies (the only labelled events)

Windows are UTC, with the end exclusive. Outside these windows, readings are unchanged from the
clean model. The labels describe these injected events and nothing else: there are no
"natural" anomalies to discover in this data.

| Event | Type | Building | Start | End | Effect |
|---|---|---|---|---|---|
{anomalies}
"""


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m wattwise.data.synthetic",
        description="Generate the deterministic synthetic sample dataset.",
    )
    parser.add_argument("--output", type=Path, required=True, help="directory to write into")
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED, help="noise seed")
    args = parser.parse_args(argv)
    digests = write(generate(args.seed), args.output)
    for name, digest in digests.items():
        print(f"{digest}  {args.output / name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
