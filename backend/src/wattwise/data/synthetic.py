"""Deterministic synthetic energy data: a small, clearly labelled fixture for tests and demos.

Nothing produced here is a measurement from a real building. The *scenario* (sites, buildings,
injected anomalies) is fixed and versioned; the seed only controls random noise. Same seed and
same locked dependencies produce byte-identical files.

Consumption is generated in each building's local time (occupancy schedules, weekends) and
stored in UTC, exercising the contract's time handling. Usage:

    uv run python -m wattwise.data.synthetic --output ../data/sample/synthetic
"""

