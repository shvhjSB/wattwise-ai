FloatArray = npt.NDArray[np.float64]

#: Bump when the generated output changes intentionally.
GENERATOR_VERSION: Final = "1"
DEFAULT_SEED: Final = 2016
START: Final = pd.Timestamp("2016-01-04T00:00:00Z")  # a Monday
DAYS: Final = 56
LABEL_SOURCE: Final = "synthetic_injection"
NOTICE: Final = (
    "SYNTHETIC DATA. Generated by wattwise.data.synthetic; these are not measurements from "
    "real buildings, and the anomaly labels describe deliberately injected events only."
)

#: Outdoor temperature below which buildings draw electric heating.
BALANCE_POINT_C: Final = 15.5
#: Local hours treated as night for the overnight base-load anomaly: 20:00-06:00.
NIGHT_START_HOUR: Final = 20
NIGHT_END_HOUR: Final = 6


@dataclass(frozen=True)
class Site:
    site_id: str
    timezone: str
    mean_temperature_c: float
    warming_c_per_day: float
    daily_sd_c: float
    diurnal_amplitude_c: float


@dataclass(frozen=True)
class Building:
    """Load model: (base + occupied * occupancy + heating) * (1 + noise), in kW = kWh per hour."""

    building_id: str
    site_id: str
    primary_use: str
    floor_area_m2: float
    base_kw: float
    occupied_kw: float
    opens_hour: float
    closes_hour: float
    weekend_occupancy: float
    heating_kw_per_c: float
    noise_sd: float

    @property
    def meter_id(self) -> str:
        return f"{self.building_id}:{MeterType.ELECTRICITY.value}"


class AnomalyType(StrEnum):
    SPIKE = "spike"
    SUSTAINED_EXCESS = "sustained_excess"
    OVERNIGHT_BASELOAD = "overnight_baseload"
    GRADUAL_DRIFT = "gradual_drift"
    FLATLINE = "flatline"
    MISSING_DATA = "missing_data"


class Effect(StrEnum):
    MULTIPLY = "multiply"  # value *= effect_value
    ADD_AT_NIGHT = "add_at_night"  # value += effect_value during local night hours
    RAMP_TO = "ramp_to"  # factor rises linearly from 1 to effect_value across the window
    HOLD = "hold"  # meter stuck at the window's first value
    REMOVE = "remove"  # readings missing


@dataclass(frozen=True)
class Anomaly:
    """An injected event on one meter, active in [start, end) (UTC, end exclusive)."""

    event_id: str
    anomaly_type: AnomalyType
    building_id: str
    start: pd.Timestamp
    end: pd.Timestamp
    effect: Effect
    effect_value: float | None
    description: str


